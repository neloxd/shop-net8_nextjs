CREATE TABLE IF NOT EXISTS usuarios (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_usuario varchar(50) NOT NULL UNIQUE,
    password_hash varchar(300) NOT NULL,
    activo boolean NOT NULL DEFAULT true,
    CONSTRAINT ck_usuario_normalizado CHECK (nombre_usuario = lower(btrim(nombre_usuario)) AND length(nombre_usuario) > 0)
);

CREATE TABLE IF NOT EXISTS tiendas (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(120) NOT NULL,
    categoria varchar(30) NOT NULL,
    activo boolean NOT NULL DEFAULT true,
    creado_en timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_tienda_nombre CHECK (char_length(btrim(nombre)) BETWEEN 2 AND 120),
    CONSTRAINT ck_tienda_categoria CHECK (categoria IN ('Moda', 'Restaurantes', 'Tecnología', 'Hogar'))
);

CREATE INDEX IF NOT EXISTS ix_tiendas_nombre ON tiendas (nombre);
CREATE INDEX IF NOT EXISTS ix_tiendas_categoria ON tiendas (categoria);

